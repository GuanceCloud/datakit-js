var MUTATION_SERIALIZATION_SLICE_MS = 4
var MUTATION_SERIALIZATION_EMIT_DELAY_MS = 16

/**
 * Buffers and aggregate mutations generated by a MutationObserver into MutationPayload
 */
export function startMutationObserver(
  mutationCallback,
  configuration,
  shadowRootsController,
  target,
  mutationPerfCb
) {
  var MutationObserver = getMutationObserverConstructor()
  if (!MutationObserver) {
    return { stop: noop, flush: noop, reset: noop }
  }

  var mutationTasksController = createMutationTasksController(
    mutationCallback,
    configuration,
    shadowRootsController
  )

  var mutationBatch = createMutationBatch(function (mutations) {
    var processStart = getCurrentTime()
    processMutations(
      mutations.concat(observer.takeRecords()),
      mutationCallback,
      configuration,
      shadowRootsController,
      mutationTasksController
    )
    if (mutationPerfCb) {
      mutationPerfCb({
        processMutationsCount: 1,
        processMutationsDuration: getCurrentTime() - processStart
      })
    }
  })

  var observer = new MutationObserver(monitor(mutationBatch.addMutations))
  try {
    observer.observe(target, {
      attributeOldValue: true,
      attributes: true,
      characterData: true,
      characterDataOldValue: true,
      childList: true,
      subtree: true
    })
  } catch (err) {}

  return {
    stop: function () {
      observer.disconnect()
      mutationBatch.stop()
      mutationTasksController.stop()
    },
    flush: function () {
      mutationBatch.flush()
      mutationTasksController.flush()
    },
    reset: function () {
      if (mutationBatch.reset) {
        mutationBatch.reset()
      }
      mutationTasksController.reset()
    }
  }
}

